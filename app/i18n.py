def detect_language(request, ui_lang: str = "auto") -> str:
    """Resolve the UI language: cookie wins, then config, then browser header."""
    cookie_lang = request.cookies.get(LANG_COOKIE)
    if cookie_lang in (LANG_EN, LANG_ZH):
        return cookie_lang
    if ui_lang in (LANG_EN, LANG_ZH):
        return ui_lang
    header = request.headers.get("accept-language", "")
    first = header.split(",")[0].strip().lower()
    if first.startswith("zh"):
        return LANG_ZH
    return LANG_EN


def get_strings(lang: str) -> dict:
    return STRINGS.get(lang, STRINGS[LANG_EN])
